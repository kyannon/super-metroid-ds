#!/usr/bin/env python3
"""Embeds the UI font (assets/fonts) in src/fonts_data.c.

    tools/embed_fonts.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [("sm_font", "super-metroid-large-alt-snes.otf")]

lines = ["/* Generated by tools/embed_fonts.py - do not edit. */", '#include "fonts_data.h"', ""]
for name, fn in FONTS:
    data = open(os.path.join(ROOT, "assets", "fonts", fn), "rb").read()
    lines.append(f"static const unsigned char {name}_otf[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
lines.append("")
lines.append("const EmbeddedFont embeddedFonts[EMBEDDED_FONT_COUNT] = {")
for name, _ in FONTS:
    lines.append(f"\t{{ {name}_otf, sizeof({name}_otf) }},")
lines.append("};")
with open(os.path.join(ROOT, "src", "fonts_data.c"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("src/fonts_data.c:", ", ".join(fn for _, fn in FONTS))
